"""Extract the tagline glyphs ("Code Without Borders.", Poppins Light) as SVG paths -> src/components/logoGlyphs.ts.
Usage (from app/): python scripts/make-logo-glyphs.py"""
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

BASE = 'node_modules/@expo-google-fonts/poppins'
SETS = {'tag': ('300Light/Poppins_300Light.ttf', 'Code Without Borders.'.replace(' ', ''))}

out = ['// Generated by scripts/make-logo-glyphs.py from Poppins (OFL). Units: 1000/em, y down, baseline at 0.', '']
for name, (file, chars) in SETS.items():
    font = TTFont(f'{BASE}/{file}')
    gs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font['hmtx']
    out.append(f'export const {name.upper()}: Record<string, {{ d: string; adv: number }}> = {{')
    for ch in sorted(set(chars)):
        g = cmap[ord(ch)]
        pen = SVGPathPen(gs, ntos=lambda v: f'{v:g}')
        gs[g].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
        out.append(f"  '{ch}': {{ adv: {hmtx[g][0]}, d: '{pen.getCommands()}' }},")
    out.append('};')
    out.append('')
out.append(f"export const TAG_SPACE = {TTFont(f'{BASE}/300Light/Poppins_300Light.ttf')['hmtx'][TTFont(f'{BASE}/300Light/Poppins_300Light.ttf').getBestCmap()[32]][0]};")
open('src/components/logoGlyphs.ts', 'w', newline='\n').write('\n'.join(out) + '\n')
